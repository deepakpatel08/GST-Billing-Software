def archive_business(business_id):
    bid=int(business_id)
    with get_connection() as conn:
        row=conn.execute("SELECT business_name,active FROM businesses WHERE id=?",(bid,)).fetchone()
        if not row: raise ValueError("Business not found.")
        if not row["active"]: raise ValueError("Business is already archived.")
        if conn.execute("SELECT COUNT(*) c FROM businesses WHERE active=1").fetchone()["c"] <= 1:
            raise ValueError("The last active Business cannot be archived.")
        conn.execute("UPDATE businesses SET active=0,archived_at=CURRENT_TIMESTAMP,updated_at=CURRENT_TIMESTAMP WHERE id=?",(bid,))
        name=row["business_name"]
    log_audit("ARCHIVE","BUSINESS",bid,name,"Business archived",business_id=bid)
    return name


def restore_business(business_id):
    bid=int(business_id)
    with get_connection() as conn:
        row=conn.execute("SELECT business_name FROM businesses WHERE id=?",(bid,)).fetchone()
        if not row: raise ValueError("Business not found.")
        conn.execute("UPDATE businesses SET active=1,archived_at='',updated_at=CURRENT_TIMESTAMP WHERE id=?",(bid,))
        name=row["business_name"]
    log_audit("RESTORE","BUSINESS",bid,name,"Business restored",business_id=bid)
    return name


