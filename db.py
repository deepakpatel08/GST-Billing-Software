def _ensure_tenant_columns(conn):
    _ensure_column(conn, "businesses", "created_by_user_id", "INTEGER")
    for table in ("clients", "invoices", "item_master"):
        definition = "INTEGER NOT NULL DEFAULT 1"
        _ensure_column(conn, table, "business_id", definition)


def _ensure_access_table(conn):
    conn.execute("""
        CREATE TABLE IF NOT EXISTS user_business_access (
            user_id INTEGER NOT NULL,
            business_id INTEGER NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY(user_id, business_id),
            FOREIGN KEY(user_id) REFERENCES app_users(id) ON DELETE CASCADE,
            FOREIGN KEY(business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_uba_user ON user_business_access(user_id)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_uba_business ON user_business_access(business_id)")


def _ensure_application_settings(conn):
    conn.execute("""
        CREATE TABLE IF NOT EXISTS application_settings (
            setting_key TEXT PRIMARY KEY,
            setting_value TEXT NOT NULL DEFAULT '',
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    if conn.backend == "postgresql":
        conn.execute(
            "INSERT INTO application_settings(setting_key,setting_value) VALUES(?,?) ON CONFLICT(setting_key) DO NOTHING",
            ("allow_user_business_creation", "0")
        )
    else:
        conn.execute(
            "INSERT OR IGNORE INTO application_settings(setting_key,setting_value) VALUES(?,?)",
            ("allow_user_business_creation", "0")
        )


def get_application_setting(key, default=""):
    with get_connection() as conn:
        row = conn.execute(
            "SELECT setting_value FROM application_settings WHERE setting_key=?", (key,)
        ).fetchone()
        return row["setting_value"] if row else default


def set_application_setting(key, value):
    with get_connection() as conn:
        if conn.backend == "postgresql":
            conn.execute(
                "INSERT INTO application_settings(setting_key,setting_value,updated_at) VALUES(?,?,CURRENT_TIMESTAMP) "
                "ON CONFLICT(setting_key) DO UPDATE SET setting_value=EXCLUDED.setting_value, updated_at=CURRENT_TIMESTAMP",
                (key, str(value))
            )
        else:
            conn.execute(
                "INSERT OR REPLACE INTO application_settings(setting_key,setting_value,updated_at) VALUES(?,?,CURRENT_TIMESTAMP)",
                (key, str(value))
            )


def allow_user_business_creation():
    return get_application_setting("allow_user_business_creation", "0") == "1"


def init_db():
    with get_connection() as conn:
        # Keep the original schema for backward compatibility.
        conn.executescript("""
        CREATE TABLE IF NOT EXISTS business_profile (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            business_name TEXT NOT NULL DEFAULT '',
            gstin TEXT NOT NULL DEFAULT '',
            address TEXT NOT NULL DEFAULT '',
            state TEXT NOT NULL DEFAULT '',
            state_code TEXT NOT NULL DEFAULT '',
            account_no TEXT NOT NULL DEFAULT '',
            ifsc TEXT NOT NULL DEFAULT '',
            branch TEXT NOT NULL DEFAULT '',
            logo_path TEXT NOT NULL DEFAULT '',
            invoice_prefix TEXT NOT NULL DEFAULT 'INV',
            invoice_separator TEXT NOT NULL DEFAULT '/',
            invoice_digits INTEGER NOT NULL DEFAULT 3,
            default_state TEXT NOT NULL DEFAULT 'Maharashtra',
            default_state_code TEXT NOT NULL DEFAULT '27',
            default_unit TEXT NOT NULL DEFAULT 'NOS',
            default_gst_rate DOUBLE PRECISION NOT NULL DEFAULT 18,
            default_invoice_notes TEXT NOT NULL DEFAULT '',
            default_report_period TEXT NOT NULL DEFAULT 'Current Month',
            invoice_sequence_start INTEGER NOT NULL DEFAULT 1
        );
        CREATE TABLE IF NOT EXISTS clients (
            id INTEGER PRIMARY KEY,
            name TEXT NOT NULL,
            gstin TEXT NOT NULL DEFAULT '',
            address TEXT NOT NULL DEFAULT '',
            state TEXT NOT NULL,
            state_code TEXT NOT NULL,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS invoices (
            id INTEGER PRIMARY KEY,
            invoice_no TEXT NOT NULL,
            invoice_date TEXT NOT NULL,
            client_id INTEGER NOT NULL,
            place_of_supply_state TEXT NOT NULL,
            place_of_supply_code TEXT NOT NULL,
            tax_type TEXT NOT NULL,
            subtotal DOUBLE PRECISION NOT NULL DEFAULT 0,
            discount_total DOUBLE PRECISION NOT NULL DEFAULT 0,
            taxable_total DOUBLE PRECISION NOT NULL DEFAULT 0,
            cgst_total DOUBLE PRECISION NOT NULL DEFAULT 0,
            sgst_total DOUBLE PRECISION NOT NULL DEFAULT 0,
            igst_total DOUBLE PRECISION NOT NULL DEFAULT 0,
            grand_total DOUBLE PRECISION NOT NULL DEFAULT 0,
            amount_in_words TEXT NOT NULL DEFAULT '',
            notes TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS invoice_items (
            id INTEGER PRIMARY KEY,
            invoice_id INTEGER NOT NULL,
            description TEXT NOT NULL,
            hsn_sac TEXT NOT NULL DEFAULT '',
            quantity DOUBLE PRECISION NOT NULL DEFAULT 0,
            unit TEXT NOT NULL DEFAULT 'NOS',
            rate DOUBLE PRECISION NOT NULL DEFAULT 0,
            discount_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
            gross_value DOUBLE PRECISION NOT NULL DEFAULT 0,
            discount_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
            taxable_value DOUBLE PRECISION NOT NULL DEFAULT 0,
            gst_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
            cgst_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
            sgst_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
            igst_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
            cgst_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
            sgst_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
            igst_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
            line_total DOUBLE PRECISION NOT NULL DEFAULT 0
        );
        CREATE TABLE IF NOT EXISTS item_master (
            id INTEGER PRIMARY KEY,
            description TEXT NOT NULL,
            hsn_sac TEXT NOT NULL DEFAULT '',
            unit TEXT NOT NULL DEFAULT 'NOS',
            default_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
            gst_rate DOUBLE PRECISION NOT NULL DEFAULT 18,
            active INTEGER NOT NULL DEFAULT 1,
            created_by_user_id INTEGER,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS app_users (
            id INTEGER PRIMARY KEY,
            username TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'Admin',
            active INTEGER NOT NULL DEFAULT 1,
            created_by_user_id INTEGER,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            failed_login_count INTEGER NOT NULL DEFAULT 0,
            locked_until TEXT NOT NULL DEFAULT '',
            last_login_at TEXT NOT NULL DEFAULT ''
        );
        """)

        # Add columns introduced in previous releases.
        for col, definition in {
            "default_state": "TEXT NOT NULL DEFAULT 'Maharashtra'",
            "default_state_code": "TEXT NOT NULL DEFAULT '27'",
            "default_unit": "TEXT NOT NULL DEFAULT 'NOS'",
            "default_gst_rate": "DOUBLE PRECISION NOT NULL DEFAULT 18",
            "default_invoice_notes": "TEXT NOT NULL DEFAULT ''",
            "default_report_period": "TEXT NOT NULL DEFAULT 'Current Month'",
            "invoice_sequence_start": "INTEGER NOT NULL DEFAULT 1",
        }.items():
            _ensure_column(conn, "business_profile", col, definition)

        for col, definition in {
            "failed_login_count": "INTEGER NOT NULL DEFAULT 0",
            "locked_until": "TEXT NOT NULL DEFAULT ''",
            "last_login_at": "TEXT NOT NULL DEFAULT ''",
        }.items():
            _ensure_column(conn, "app_users", col, definition)

        _ensure_businesses(conn)

        # Create the first business from the existing singleton profile.
        old = conn.execute("SELECT * FROM business_profile WHERE id=1").fetchone()
        existing_business = conn.execute("SELECT id FROM businesses WHERE id=1").fetchone()
        if not existing_business:
            if old:
                cols = [
                    "business_name","gstin","address","state","state_code","account_no","ifsc","branch",
                    "logo_path","invoice_prefix","invoice_separator","invoice_digits","default_state",
                    "default_state_code","default_unit","default_gst_rate","default_invoice_notes",
                    "default_report_period","invoice_sequence_start"
                ]
                values = [old[c] for c in cols]
                conn.execute(
                    f"""INSERT INTO businesses(id,{','.join(cols)}) VALUES(1,{','.join('?' for _ in cols)})""",
                    tuple(values)
                )
            else:
                conn.execute("INSERT INTO businesses(id) VALUES(1)")

        _ensure_tenant_columns(conn)
        _ensure_access_table(conn)
        _ensure_application_settings(conn)

        # v1.2 freeze features: business lifecycle, invoice status/payment, item codes and audit log.
        _ensure_column(conn, "businesses", "archived_at", "TEXT NOT NULL DEFAULT ''")
        _ensure_column(conn, "invoices", "status", "TEXT NOT NULL DEFAULT 'ACTIVE'")
        _ensure_column(conn, "invoices", "cancellation_reason", "TEXT NOT NULL DEFAULT ''")
        _ensure_column(conn, "invoices", "cancelled_at", "TEXT NOT NULL DEFAULT ''")
        _ensure_column(conn, "invoices", "cancelled_by_user_id", "INTEGER")
        _ensure_column(conn, "invoices", "payment_status", "TEXT NOT NULL DEFAULT 'Unpaid'")
        _ensure_column(conn, "invoices", "amount_received", "DOUBLE PRECISION NOT NULL DEFAULT 0")
        _ensure_column(conn, "invoices", "balance_due", "DOUBLE PRECISION NOT NULL DEFAULT 0")
        _ensure_column(conn, "item_master", "item_code", "TEXT NOT NULL DEFAULT ''")
        audit_id_definition = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if conn.backend == "postgresql" else "INTEGER PRIMARY KEY AUTOINCREMENT"
        conn.execute(f"""CREATE TABLE IF NOT EXISTS audit_logs (
            id {audit_id_definition}, user_id INTEGER, business_id INTEGER,
            action TEXT NOT NULL, entity_type TEXT NOT NULL, entity_id INTEGER,
            reference TEXT NOT NULL DEFAULT '', details TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_audit_business ON audit_logs(business_id, created_at DESC)")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_logs(user_id, created_at DESC)")
        conn.execute("UPDATE invoices SET status='ACTIVE' WHERE status IS NULL OR status=''")
        conn.execute("UPDATE invoices SET payment_status='Unpaid' WHERE payment_status IS NULL OR payment_status=''")
        conn.execute("UPDATE invoices SET amount_received=0 WHERE amount_received IS NULL")
        conn.execute("UPDATE invoices SET balance_due=grand_total-amount_received WHERE balance_due IS NULL")
        for brow in conn.execute("SELECT id FROM businesses ORDER BY id").fetchall():
            bid = brow["id"]
            missing = conn.execute("SELECT id FROM item_master WHERE business_id=? AND (item_code IS NULL OR item_code='') ORDER BY id", (bid,)).fetchall()
            for idx, row in enumerate(missing, 1):
                conn.execute("UPDATE item_master SET item_code=? WHERE id=? AND business_id=?", (f"ITM{idx:03d}", row["id"], bid))
        if conn.backend == "postgresql":
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_item_business_code ON item_master(business_id, item_code) WHERE item_code <> ''")

        if conn.backend == "postgresql":
            conn.execute("""
                SELECT setval(
                    pg_get_serial_sequence('businesses','id'),
                    COALESCE(MAX(id),1),
                    MAX(id) IS NOT NULL
                )
                FROM businesses
            """)

        # Existing records belong to the original business.
        conn.execute("UPDATE clients SET business_id=1 WHERE business_id IS NULL")
        conn.execute("UPDATE invoices SET business_id=1 WHERE business_id IS NULL")
        conn.execute("UPDATE item_master SET business_id=1 WHERE business_id IS NULL")

        # Give every existing user access to the original business.
        users = conn.execute("SELECT id FROM app_users").fetchall()
        for user in users:
            conn.execute(
                "INSERT INTO user_business_access(user_id,business_id) VALUES(?,1) ON CONFLICT DO NOTHING"
                if conn.backend == "postgresql"
                else "INSERT OR IGNORE INTO user_business_access(user_id,business_id) VALUES(?,1)",
                (user["id"],)
            )

        # PostgreSQL: remove the old global invoice uniqueness so each business
        # can independently use the same invoice series.
        if conn.backend == "postgresql":
            conn.execute("ALTER TABLE invoices DROP CONSTRAINT IF EXISTS invoices_invoice_no_key")
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_invoice_business_no ON invoices(business_id, invoice_no)")
            conn.execute("ALTER TABLE item_master DROP CONSTRAINT IF EXISTS item_master_description_key")
            conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_item_business_description ON item_master(business_id, LOWER(description))")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_clients_business ON clients(business_id)")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_invoices_business ON invoices(business_id)")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_items_business ON item_master(business_id)")
        else:
            conn.execute("CREATE INDEX IF NOT EXISTS idx_clients_business ON clients(business_id)")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_invoices_business ON invoices(business_id)")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_items_business ON item_master(business_id)")


def row_to_dict(row):
    return dict(row) if row else None


def _current_user_id():
    try:
        import streamlit as st
        return (st.session_state.get("authenticated_user") or {}).get("id")
    except Exception:
        return None


def log_audit(action, entity_type, entity_id=None, reference="", details="", user_id=None, business_id=None):
    uid = user_id if user_id is not None else _current_user_id()
    bid = business_id if business_id is not None else _active_business_id()
    with get_connection() as conn:
        conn.execute("""INSERT INTO audit_logs(user_id,business_id,action,entity_type,entity_id,reference,details)
                       VALUES(?,?,?,?,?,?,?)""", (uid,bid,action,entity_type,entity_id,reference or "",details or ""))


