def _upsert_item_masters(conn, items):
    bid=_active_business_id()
    for item in items:
        desc=item["description"].strip()
        row=conn.execute("SELECT id,item_code FROM item_master WHERE business_id=? AND LOWER(description)=LOWER(?)",(bid,desc)).fetchone()
        if row:
            conn.execute("UPDATE item_master SET hsn_sac=?,unit=?,default_rate=?,gst_rate=?,active=1,updated_at=CURRENT_TIMESTAMP WHERE id=?",
                         (item["hsn_sac"].strip(),item["unit"],item["rate"],item["gst_rate"],row["id"]))
        else:
            count=conn.execute("SELECT COUNT(*) c FROM item_master WHERE business_id=?",(bid,)).fetchone()["c"]
            code=f"ITM{int(count)+1:03d}"
            # Avoid collision if an item was deleted/reused.
            while conn.execute("SELECT 1 FROM item_master WHERE business_id=? AND item_code=?",(bid,code)).fetchone():
                count+=1; code=f"ITM{int(count)+1:03d}"
            conn.execute("INSERT INTO item_master(item_code,description,hsn_sac,unit,default_rate,gst_rate,active,business_id) VALUES(?,?,?,?,?,?,1,?)",
                         (code,desc,item["hsn_sac"].strip(),item["unit"],item["rate"],item["gst_rate"],bid))


