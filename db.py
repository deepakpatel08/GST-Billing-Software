def list_invoices(start_date=None,end_date=None,client_id=None,search_text=None,include_cancelled=False):
    bid = _active_business_id()
    sql = """
        SELECT i.*,c.name client_name,c.gstin client_gstin,c.state client_state,c.state_code client_state_code
        FROM invoices i JOIN clients c ON c.id=i.client_id AND c.business_id=i.business_id
    """
    params, clauses = [], ["i.business_id=?"]
    params.append(bid)
    if not include_cancelled:
        clauses.append("i.status <> 'CANCELLED'")
    if start_date:
        clauses.append("i.invoice_date>=?"); params.append(start_date)
    if end_date:
        clauses.append("i.invoice_date<=?"); params.append(end_date)
    if client_id:
        clauses.append("i.client_id=?"); params.append(client_id)
    if search_text:
        clauses.append("(i.invoice_no LIKE ? OR c.name LIKE ? OR c.gstin LIKE ?)")
        term=f"%{search_text.strip()}%"
        params.extend([term,term,term])
    sql += " WHERE " + " AND ".join(clauses) + " ORDER BY i.invoice_date DESC,i.id DESC"
    with get_connection() as conn:
        return [dict(r) for r in conn.execute(sql,params).fetchall()]


