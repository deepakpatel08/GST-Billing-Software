def _get_database_url():
    value = os.getenv("DATABASE_URL", "").strip()
    if value:
        return value
    try:
        import streamlit as st
        return str(st.secrets.get("DATABASE_URL", "")).strip()
    except Exception:
        return ""


def database_backend():
    return "postgresql" if _get_database_url() else "sqlite"


class _DBConnection:
    def __init__(self):
        self.backend = database_backend()
        if self.backend == "postgresql":
            import psycopg2
            from psycopg2.extras import RealDictCursor
            self.conn = psycopg2.connect(_get_database_url())
            self.conn.autocommit = False
            self.cursor_factory = RealDictCursor
        else:
            self.conn = sqlite3.connect(DB_PATH)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")

    def execute(self, sql, params=()):
        if self.backend == "postgresql":
            cur = self.conn.cursor(cursor_factory=self.cursor_factory)
            cur.execute(sql.replace("?", "%s"), params)
            return cur
        return self.conn.execute(sql, params)

    def executemany(self, sql, seq):
        if self.backend == "postgresql":
            cur = self.conn.cursor(cursor_factory=self.cursor_factory)
            cur.executemany(sql.replace("?", "%s"), seq)
            return cur
        return self.conn.executemany(sql, seq)

    def executescript(self, sql):
        if self.backend == "postgresql":
            cur = self.conn.cursor(cursor_factory=self.cursor_factory)
            for statement in sql.split(";"):
                statement = statement.strip()
                if statement:
                    cur.execute(statement)
            return cur
        return self.conn.executescript(sql)

    def commit(self):
        self.conn.commit()

    def rollback(self):
        self.conn.rollback()

    def close(self):
        self.conn.close()


@contextmanager
def get_connection():
    db = _DBConnection()
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


